-- ========================
-- ENUM TYPES
-- ========================
CREATE TYPE alert_type AS ENUM ('spike', 'high_risk', 'trend_reversal', 'new_hotspot', 'data_quality', 'sos_escalation');
CREATE TYPE alert_severity AS ENUM ('critical', 'high', 'medium', 'low');
CREATE TYPE audit_action AS ENUM ('create', 'update', 'delete', 'view', 'export', 'login', 'logout', 'sos_trigger', 'sos_acknowledge');

-- ========================
-- ALERTS
-- ========================
CREATE TABLE alerts (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    zone_id UUID NOT NULL REFERENCES zones(id) ON DELETE RESTRICT,
    alert_type alert_type NOT NULL,
    severity alert_severity NOT NULL,
    title VARCHAR(300) NOT NULL,
    message TEXT NOT NULL,

    -- Acknowledgment
    is_acknowledged BOOLEAN NOT NULL DEFAULT FALSE,
    acknowledged_by UUID REFERENCES users(id),
    acknowledged_at TIMESTAMPTZ,
    resolution_notes TEXT,

    -- Auto-generated by which agent/system
    generated_by VARCHAR(100), -- 'data_analyst_agent', 'risk_engine', 'sos_service'

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ
);

CREATE INDEX idx_alerts_zone ON alerts(zone_id);
CREATE INDEX idx_alerts_severity ON alerts(severity);
CREATE INDEX idx_alerts_unack ON alerts(id) WHERE is_acknowledged = FALSE;
CREATE INDEX idx_alerts_created ON alerts(created_at DESC);
-- NOW() is STABLE, not IMMUTABLE, so it cannot appear in an index predicate.
-- Index expires_at across unacknowledged alerts instead; callers apply the time
-- comparison at query time:
--   WHERE is_acknowledged = FALSE AND (expires_at IS NULL OR expires_at > NOW())
CREATE INDEX idx_alerts_active ON alerts(expires_at) WHERE is_acknowledged = FALSE;

-- ========================
-- AUDIT LOG (immutable — no updates, no deletes)
-- ========================
CREATE TABLE audit_logs (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID REFERENCES users(id),
    action audit_action NOT NULL,
    entity_type VARCHAR(100) NOT NULL,  -- 'incident', 'zone', 'user', etc.
    entity_id UUID,
    old_values JSONB,
    new_values JSONB,
    ip_address INET,
    user_agent TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Partition-ready: indexed by time for efficient querying
CREATE INDEX idx_audit_logs_user ON audit_logs(user_id);
CREATE INDEX idx_audit_logs_action ON audit_logs(action);
CREATE INDEX idx_audit_logs_entity ON audit_logs(entity_type, entity_id);
CREATE INDEX idx_audit_logs_created ON audit_logs(created_at DESC);
